money = int(input("Баланс карты?: "))
transfer = int(input("Сумма перевода?: "))
status = input("Подтверждение от банка?: ")
type = input("Обычный или Золотой аккаунт?: ")
if money >= transfer and status == "Да":
    print("Операция разрешена. Деньги отправлены!")
elif status == "Нет" and type == "Золотой":
    print("Нужно подтверждение, но для вашего VIP-аккаунта мы сделаем исключение. Операция одобрена!")
elif money < transfer or transfer > 100000:
    print("Ошибка: недостаточно средств или превышен лимит в 100 000")
else:
    print("Операция отклонена. Обратитесь в поддержку")