name = input("Имя?: ")
print(f"Добро пожаловать в Python, {name}.")
class1 = input("Класс?: ")
if class1 == "Воин":
    hp = 200
    mana = 0
    print("Вы выбрали Воина. У вас много здоровья.")
elif class1 == "Лучник":
    hp = 120
    mana = 50
    print("Вы выбрали Лучника. Вы очень меткий!")
elif class1 == "Маг":
    hp = 100
    mana = 150
    print("Вы выбрали Мага. Ваша сила в заклинаниях")
else:
    hp = 50
    mana = 10
    print("Класс не распознан. Вы — обычный крестьянин")
time = int(input("Сколько лет играете в игры?: "))
if time > 5:
    hp += 50
    print("Ого, вы опытный игрок! Ловите бонус к здоровью")
else:
    print("Удачи в вашем первом приключении!")

print(f"\nВаши итоговые характеристики:\nЗдоровье - {hp}\nМана: {mana}")