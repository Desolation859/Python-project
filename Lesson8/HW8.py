a = input("На улицу выходить?: ")
if a == "Да":
    b = input("Там дождь, имеется зонтик?: ")
    if b == "Да":
        c = input("Зайти в магазин или продолжить идти?: ")
        if c == "Магазин":
            d = input("В магазине имеются зелья силы и здоровья, какое покупать?: ")
            if d == "Силы":
                print("Вы купили и выпили зелье силы! +5 к атаке!")
            else:
                print("Вы купили и выпили зелье здоровья! На вас больше нет царапин!")
        else:
            e = input("Вы на развилке, направо или налево?: ")
            if e == "Направо":
                g = input("Вы споткнулись и упали в пещеру. У вас есть факел?")
                if g == "Да":
                    h = input("Вы идете по пещере и почти поднялись но вам нужно вскарабкаться наверх. Сколько у вас силы?")
                    if h >= 10:
                        j = input("Вы выбрались из пещеры! Продолжите путешествие или вернетесь домой?")
                        if j == "Домой":
                            print("Вы ушли домой")
                        else:
                            print("Вы решаете продолжить путешествие! +5 к воле!")
                    else:
                        k = input("У вас не достаточно силы чтобы выбраться, на вас нападает зомби. Сколько у вас здоровья?")
                        if k <= 5:
                            print("Игра окончена!")
                else:
                    print("К сожалению, у вас не получается выйти из пещеры.")
            else:
                print("Вы нашли сокровище!")
    else:
        f = input("А дождевой костюм имеется?: ")
        if f == "Да":
            print("Вы выходите на улицу.")
        else:
            print("Вы остаетесь дома и умираете от скуки.")
else:
    print("Вы остаетесь дома и умираете от скуки.")